/* Generate local SVG paths from the checked-in KOSTAT 2013 preview. No network. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const geo = JSON.parse(fs.readFileSync(path.join(root, 'assets/maps/busan-districts.geojson'), 'utf8'));
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'js/map/map-catalog.js'), 'utf8'), context);
const catalog = context.window.IEBMapCatalog.districts;
const byCode = new Map(catalog.map(district => [district.code, district]));
const rings = feature => feature.geometry.type === 'Polygon'
  ? feature.geometry.coordinates : feature.geometry.coordinates.flat();
const points = geo.features.flatMap(feature => rings(feature).flat());
const minX = Math.min(...points.map(point => point[0]));
const maxX = Math.max(...points.map(point => point[0]));
const minY = Math.min(...points.map(point => point[1]));
const maxY = Math.max(...points.map(point => point[1]));
const longitudeScale = Math.cos((minY + maxY) / 2 * Math.PI / 180);
const scale = Math.min(580 / ((maxX - minX) * longitudeScale), 440 / (maxY - minY));
const width = (maxX - minX) * longitudeScale * scale;
const height = (maxY - minY) * scale;
const project = ([longitude, latitude]) => [
  +(30 + (580 - width) / 2 + (longitude - minX) * longitudeScale * scale).toFixed(1),
  +(20 + (440 - height) / 2 + (maxY - latitude) * scale).toFixed(1),
];
function centroid(ring) {
  let area = 0, x = 0, y = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const a = ring[i], b = ring[i + 1];
    const cross = a[0] * b[1] - b[0] * a[1];
    area += cross;
    x += (a[0] + b[0]) * cross;
    y += (a[1] + b[1]) * cross;
  }
  return Math.abs(area) > 1e-12 ? [x / (3 * area), y / (3 * area)] : ring[0];
}
const callouts = { jung: [360, 402], dong: [389, 358], seo: [269, 422], suyeong: [473, 291], yeonje: [560, 260] };
const districts = geo.features.map(feature => {
  const metadata = byCode.get(String(feature.properties.code));
  if (!metadata) throw new Error('Unknown boundary district code: ' + feature.properties.code);
  const polygon = rings(feature), center = centroid(polygon[0]);
  const label = project(center);
  return {
    id: metadata.id, name: metadata.name, code: metadata.code,
    path: polygon.map(ring => ring.map((point, index) => (index ? 'L' : 'M') + project(point).join(',')).join('') + 'Z').join(''),
    label: callouts[metadata.id] || label,
    ...(callouts[metadata.id] ? { anchor: label } : {}),
    center: [+center[1].toFixed(5), +center[0].toFixed(5)],
  };
});
if (districts.length !== catalog.length || new Set(districts.map(d => d.code)).size !== catalog.length) {
  throw new Error('Expected one boundary per catalog district.');
}
const result = { viewBox: '60 8 570 464', sourceYear: 2013, districts };
const header = '/* Generated by tools/build-district-map.cjs. KOSTAT 2013 simplified preview; see assets/maps/README.md. */\n';
fs.writeFileSync(path.join(root, 'js/map/district-shapes.js'), header + 'window.IEBDistrictShapes = ' + JSON.stringify(result) + ';\n');
console.log('Generated ' + districts.length + ' local SVG district paths');
